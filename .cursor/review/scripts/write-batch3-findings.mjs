function toYaml(f) {
  const esc = (s) =>
    String(s)
      .split('\n')
      .map((line, i) => (i === 0 ? line : `  ${line}`))
      .join('\n');
  return `id: ${f.id}
module_id: ${f.module_id}
severity: ${f.severity}
status: open
file: ${f.file}
lines: "${f.lines}"
category: ${f.category}
title: ${f.title}
description: |
  ${esc(f.description)}
reproduction: |
  ${esc(f.reproduction)}
impact: ${f.impact}
suggested_fix: ${f.suggested_fix}
`;
}

let count = 0;
for (const f of findings) {
  const dir = join(root, f.dir);
  mkdirSync(dir, { recursive: true });
  const path = join(dir, `${f.id}.yaml`);
  writeFileSync(path, toYaml(f), 'utf8');
  count++;
}

console.log(`Wrote ${count} YAML files`);
